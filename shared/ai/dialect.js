const MSA_TO_DZ = DZ_TO_MSA.map(([a, b]) => [b, a]);

/**
 * Algerian first-person verbs start with ن- where MSA uses أ-.
 * Applied only to a closed list of verbs so real nouns are never touched.
 */
const VERB_STEMS = [
  'حب', 'قول', 'عرف', 'شوف', 'دير', 'فكر', 'تفكر', 'نسى', 'تمنى', 'قدر', 'بكي', 'ضحك',
  'فرح', 'حزن', 'خاف', 'شتاق', 'وحش', 'جي', 'روح', 'كتب', 'قرا', 'خدم', 'سمع', 'حس',
  'بقا', 'زاد', 'سال', 'سماح', 'وعد', 'فهم', 'صدق', 'نطق', 'حكي', 'عاود',
];

/** Characters that may sit next to a word without being part of it. */
const BOUNDARY = String.raw`\s،؛:.,!?"'()«»\-`;
/** Arabic prefixes that stick to a word (و/ف/ب/ل/ك/س) and must be preserved. */
const PREFIX = '([وفبلكس]?)';

function swapWords(text, table) {
  let out = text;
  for (const [from, to] of table) {
    if (from === to) continue;
    const re = new RegExp(`(^|[${BOUNDARY}])${PREFIX}${escapeRe(from)}(?=$|[${BOUNDARY}])`, 'g');
    out = out.replace(re, (_m, pre, prefix) => `${pre}${prefix}${to}`);
  }
  return out;
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function firstPersonToMsa(text) {
  return text.replace(
    new RegExp(`(^|[${BOUNDARY}])${PREFIX}ن(${VERB_STEMS.join('|')})`, 'g'),
    (_m, pre, prefix, stem) => `${pre}${prefix}أ${stem}`,
  );
}

function firstPersonToDz(text) {
  return text.replace(
    new RegExp(`(^|[${BOUNDARY}])${PREFIX}أ(${VERB_STEMS.join('|')})`, 'g'),
    (_m, pre, prefix, stem) => `${pre}${prefix}ن${stem}`,
  );
}

/** @param {'ar-msa'|'ar-dz'|'ar-fr'|'fr'|'en'} lang */
export function toRegister(text, lang) {
  if (!text) return text;
  if (lang === 'ar-msa') return firstPersonToMsa(swapWords(text, DZ_TO_MSA));
  if (lang === 'ar-dz') return firstPersonToDz(swapWords(text, MSA_TO_DZ));
  return text;
}

/** True when the text already looks like Darija (helps us avoid double work). */
export function looksLikeDarija(text) {
  return /(^|\s)(نحب|بزاف|بصح|راك|راكي|حاجة|دروك|واش|علاش|مليح|برك|صحيت|نتوحش|بلي)(\s|$|[،.!?])/.test(
    text || '',
  );
}
